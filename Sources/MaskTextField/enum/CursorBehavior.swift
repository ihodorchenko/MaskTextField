import Foundation

/// Поведение курсора при редактировании маскированного значения.
public enum CursorBehavior {
    /// Курсор можно ставить в любое место; ввод и удаление происходят в позиции курсора.
    case free

    /// Курсор всегда стоит на первой свободной позиции ввода. Ввод и стирание
    /// возможны только последовательно (в конец и с конца); произвольно поставить
    /// курсор нельзя. Выделение трактуется как «от начала выделения до конца»:
    /// вставка в выделение отбрасывает значение справа от него.
    case sequential
}
